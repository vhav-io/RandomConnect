/* =========================
   CREATE GROUP
========================= */

if (createGroupForm) {

    createGroupForm.addEventListener(
        "submit",
        async function (event) {

            event.preventDefault();

            const groupName =
                groupNameInput
                    ? groupNameInput.value.trim()
                    : "";

            if (!groupName) {
                return;
            }

            try {

                const response =
                    await fetch(
                        `${API_URL}/api/groups`,
                        {
                            method: "POST",

                            headers: {
                                "Content-Type":
                                    "application/json"
                            },

                            body:
                                JSON.stringify({
                                    name:
                                        groupName
                                })
                        }
                    );

                const data =
                    await response.json();

                if (!response.ok) {

                    if (groupResult) {

                        groupResult.style.display =
                            "block";

                        groupResult.innerHTML = `
                            <h3>Unable to Create Group</h3>
                            <p>
                                ${data.detail ||
                                "Something went wrong."}
                            </p>
                        `;
                    }

                    return;
                }

                if (groupResult) {

                    groupResult.style.display =
                        "block";

                    groupResult.innerHTML = `
                        <h3>✓ Group Created!</h3>

                        <p>
                            Your group
                            <strong>${data.name}</strong>
                            is ready.
                        </p>

                        <p>
                            Group code:
                        </p>

                        <h2>${data.code}</h2>

                        <p>
                            Opening group chat...
                        </p>
                    `;
                }

                if (groupNameInput) {
                    groupNameInput.value = "";
                }

                setTimeout(
                    function () {

                        window.location.href =
                            `group-chat.html?code=${
                                encodeURIComponent(
                                    data.code
                                )
                            }`;

                    },
                    800
                );

            } catch (error) {

                console.error(
                    "Group creation failed:",
                    error
                );

                if (groupResult) {

                    groupResult.style.display =
                        "block";

                    groupResult.innerHTML = `
                        <h3>Connection Error</h3>

                        <p>
                            Unable to connect to the server.
                        </p>
                    `;
                }
            }
        }
    );
}


